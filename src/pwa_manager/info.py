"""
PWA Manager Info.

Shows detailed information about one PWA application.
"""


def show_info(app):

    print(
        "PWA Manager Info"
    )

    print(
        "================"
    )

    print()

    print(
        f"Name:"
    )

    print(
        app.display_name
    )

    print()

    print(
        "Source:"
    )

    print(
        app.source
    )

    print()

    print(
        "Type:"
    )

    print(
        app.app_type
    )

    print()

    print(
        "Desktop:"
    )

    print(
        app.desktop_file
    )

    print()

    print(
        "Icon:"
    )

    print(
        app.icon
    )

    print()

    print(
        "Health:"
    )

    print(
        "OK"
    )
